CREATE TABLE PEPRT_PARENT (
   PEPRT_CODIGO         CHAR(6) NOT NULL,
   PEPRT_TIPPAR         VARCHAR(50) NOT NULL,
   PRIMARY KEY (PEPRT_CODIGO)
