CREATE TABLE PEDEP_DEPAR (
   PEDEP_CODIGO         CHAR(3) NOT NULL,
   PEDEP_DESCRI         VARCHAR(50) NOT NULL,
   PRIMARY KEY (PEDEP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE GEPRO_PROYECT (
   GEPRO_CODIGO         CHAR(3) NOT NULL,
   PEDEP_CODIGO         CHAR(3),
   GEPRO_NOMBRE         VARCHAR(50) NOT NULL,
   PRIMARY KEY (GEPRO_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE GR_PEEMP_GEPRO (
   PEEMP_CODIGO         CHAR(6) NOT NULL,
   GEPRO_CODIGO         CHAR(3) NOT NULL,
   PRIMARY KEY (PEEMP_CODIGO, GEPRO_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PECAR_CARGO (
   PEDEP_CODIGO         CHAR(3) NOT NULL,
   PECAR_CODIGOCARGO    CHAR(3) NOT NULL,
   PECAR_DESCRICARGO    VARCHAR(50) NOT NULL,
   PRIMARY KEY (PEDEP_CODIGO, PECAR_CODIGOCARGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PEEMP_EMPLE (
   PEEMP_CODIGO         CHAR(6) NOT NULL,
   PEC_PEDEP_CODIGO     CHAR(3) NOT NULL,
   PECAR_CODIGOCARGO    CHAR(3) NOT NULL,
   PEE_PEEMP_CODIGO     CHAR(6),
