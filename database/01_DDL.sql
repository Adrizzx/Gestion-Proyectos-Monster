-- Historial usuario ↔ perfil
CREATE TABLE XEUXP_USUPE (
    XEPER_CODIGO    CHAR(8)     NOT NULL,
    PEEMP_CODIGO    CHAR(6)     NOT NULL,
    XEUSU_PASWD     VARCHAR(64) NOT NULL,
    XEUXP_FECASI   DATE        NOT NULL,
    XEUXP_FECRET   DATE,
    PRIMARY KEY (XEPER_CODIGO, PEEMP_CODIGO, XEUSU_PASWD, XEUXP_FECASI)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =============================================================================
-- TABLAS DE PROYECTOS
-- =============================================================================

-- Proyectos
CREATE TABLE GEPRO_PROYECT (
    GEPRO_CODIGO    CHAR(3)       NOT NULL,
    PEDEP_CODIGO    CHAR(3),
    GEPRO_NOMBRE    VARCHAR(100)  NOT NULL,
    GEPRO_DESCRI    VARCHAR(255),
    GEPRO_PRESUP    DECIMAL(12,2) NOT NULL DEFAULT 0,   -- Presupuesto (costo planificado)
    GEPRO_GASTO     DECIMAL(12,2) NOT NULL DEFAULT 0,   -- Gasto acumulado (costo real)
    GEPRO_FECINI    DATE,                               -- Fecha de inicio
    GEPRO_FECFIN    DATE,                               -- Fecha de fin estimada
    GEPRO_AVANCE    INT           NOT NULL DEFAULT 0,   -- Porcentaje de avance 0-100
    GEPRO_ESTADO    VARCHAR(20)   NOT NULL DEFAULT 'PLANIFICADO', -- PLANIFICADO | EN_PROGRESO | COMPLETADO | CANCELADO
    GEPRO_RECURS    VARCHAR(255),                       -- Recursos del proyecto (materiales, licencias, equipos)
    PRIMARY KEY (GEPRO_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Asignación empleados ↔ proyectos
CREATE TABLE GR_PEEMP_GEPRO (
    PEEMP_CODIGO    CHAR(6) NOT NULL,
