   PRIMARY KEY (PEFIR_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PEESC_ESTCIV (
   PEESC_CODIGO         CHAR(1) NOT NULL,
   PEESC_DESCRI         VARCHAR(50) NOT NULL,
   PRIMARY KEY (PEESC_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PEFAM_FAMILI (
