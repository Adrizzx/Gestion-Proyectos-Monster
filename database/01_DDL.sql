    PEEMP_DISCAP        BLOB         NOT NULL,
    PRIMARY KEY (PEEMP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Educación / Formación del empleado
