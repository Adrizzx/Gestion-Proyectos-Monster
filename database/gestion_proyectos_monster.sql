   PEEMP_FECSAL         DATE NOT NULL,
   PEEMP_DIREC          VARCHAR(200) NOT NULL,
   PEEMP_TELEF          VARCHAR(15) NOT NULL,
   PEEMP_EMAIL          VARCHAR(100) NOT NULL,
   PEEMP_CEDULA         VARCHAR(10) NOT NULL,
   PEEMP_FOTO           VARCHAR(100),
   PEEMP_CARFAM         NUMERIC(3,0) NOT NULL,
   PEEMP_PASAPO         VARCHAR(15) NOT NULL,
   PEEMP_DISCAP         BLOB NOT NULL,
   PRIMARY KEY (PEEMP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PEEDU_EDUCACION (
   PEEDU_CODIGO         CHAR(6) NOT NULL,
   PEEMP_CODIGO         CHAR(6) NOT NULL,
   PEEDU_TITULO         VARCHAR(100) NOT NULL,
   PEEDU_INSTITUCION    VARCHAR(100) NOT NULL,
   PEEDU_FECGRADO       DATE NOT NULL,
   PEEDU_FECINI         DATE NOT NULL,
   PRIMARY KEY (PEEDU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PEFIR_FIRMA (
   PEFIR_CODIGO         CHAR(6) NOT NULL,
   PEEMP_CODIGO         CHAR(6) NOT NULL,
   PEFIR_DESCRIP        VARCHAR(200),
   PEFIR_RUTA           VARCHAR(200),
